// Ohio's municipal tax credit mechanic: a resident who works in a *different* Ohio
// municipality gets a credit from their HOME municipality against tax paid to the WORK
// municipality. Each home municipality sets its own credit independently. The value here
// is each municipality's published "Credit Rate" / "Credit Limit" -- the maximum percent
// of income the home municipality will credit against tax paid elsewhere (RITA and CCA
// both also publish a separate "Credit Factor" multiplier, not captured in this compact
// table; consult the source tables directly if that finer distinction is needed).
//
// administeredBy: "RITA" | "CCA" | "self" (self-administered by the city).
//
// Coverage caveats (see conversation report for full detail):
//  - 460 municipalities/villages covered: 416 RITA members, 36 CCA members, 8 large
//    self-administered cities. This is NOT all ~600-700 Ohio taxing municipalities --
//    smaller self-administered cities outside RITA/CCA (e.g. many Columbus-area suburbs,
//    Springfield-area, etc. that run their own tax dept but are not RITA/CCA members and
//    are not one of the 8 largest cities) are NOT included and would need individual
//    verification against their own ordinances.
//  - Special taxing districts (JEDD/JEDZ/ENTPZ, company-specific revenue-sharing rate
//    zones) were deliberately excluded -- they are not places of residence, so they don't
//    belong in a home-municipality lookup.
//  - Canton's credit rate/limit could not be confirmed from a readable primary source in
//    this pass (its resident rate of 2% is well corroborated); credit is null pending
//    verification of Canton Codified Ordinances Sec. 182.081.
//  - Zip-to-municipality mapping is NOT included here and is not necessarily reliable in
//    Ohio: many zip codes straddle multiple taxing municipalities (this is common in
//    dense Cuyahoga/Franklin/Hamilton county suburbs), so a zip lookup should not be
//    assumed 1:1 without a separate verified crosswalk (e.g. Ohio Dept. of Taxation's
//    address-based "Finder" lookup, queried per-address rather than per-zip).
